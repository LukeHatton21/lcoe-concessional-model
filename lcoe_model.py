    def process_hydro_shapefiles(self, data_path, lat_col, lon_col):

        # Extract shapefile as geopandas
        gdf = gpd.read_file(data_path).to_crs("EPSG:4326")

        # Extract what is needed
        df = gdf[[lat_col, lon_col, "POWER_MW"]].rename(columns={"POWER_MW":"Capacity_MW", lat_col: "latitude", lon_col:"longitude"})
        grid_ds = self.solar_processed
        grid_lat = grid_ds["latitude"].values
        grid_lon = grid_ds["longitude"].values

        if grid_lon.min() >= 0 and df["longitude"].min() < 0:
            df["longitude"] = (df["longitude"] + 360) % 360

        if not np.allclose(np.diff(grid_lat), np.diff(grid_lat)[0]):
            raise ValueError("Latitude grid is not regular")

        if not np.allclose(np.diff(grid_lon), np.diff(grid_lon)[0]):
            raise ValueError("Longitude grid is not regular")

        dlat = grid_lat[1] - grid_lat[0]
        dlon = grid_lon[1] - grid_lon[0]

        # Convert to nearest grid indices
        lat_idx = np.round((df["latitude"].to_numpy() - grid_lat[0]) / dlat).astype(int)
        lon_idx = np.round((df["longitude"].to_numpy() - grid_lon[0]) / dlon).astype(int)

        valid = (
                (lat_idx >= 0) & (lat_idx < len(grid_lat)) &
                (lon_idx >= 0) & (lon_idx < len(grid_lon))
        )

        lat_idx = lat_idx[valid]
        lon_idx = lon_idx[valid]
        capacity_vals = df["Capacity_MW"].to_numpy()[valid]


        if "GDW_reservoirs_v1_0.shp" in data_path:
            plant_count = np.zeros((len(grid_lat), len(grid_lon)), dtype=int)
            np.add.at(plant_count, (lat_idx, lon_idx), 1)
            plant_capacity_da = xr.DataArray(
                plant_count,
                coords={"latitude": grid_ds["latitude"], "longitude": grid_ds["longitude"]},
                dims=("latitude", "longitude"),
                name="Capacity_MW"
            )
        else:
            plant_count = np.zeros((len(grid_lat), len(grid_lon)), dtype=int)
            np.add.at(plant_count, (lat_idx, lon_idx), 1)
            plant_capacity_da = xr.DataArray(
                plant_count,
                coords={"latitude": grid_ds["latitude"], "longitude": grid_ds["longitude"]},
                dims=("latitude", "longitude"),
                name="Capacity_MW"
            )

        return plant_capacity_da

    def fill_country_gaps(self):

        # Get waccs
        country_waccs = self.country_wacc_mapping

        # Get region information
        country_waccs = country_waccs[["Country code", "index", "solar_pv_wacc", "onshore_wacc", "offshore_wacc", "hydro_wacc", "geothermal_wacc", "bioenergy_wacc"]]
        country_waccs = pd.merge(country_waccs, self.country_mapping[["Country code", "sub-region"]], how="left", on="Country code")


        # Find maximums and extract
        region_max = country_waccs.groupby("sub-region").agg("max").reset_index().add_suffix("_max")

        # Merge back onto original
        country_waccs = pd.merge(country_waccs, region_max.drop(columns=["index_max", "Country code_max"]), how="left", left_on=["sub-region"], right_on="sub-region_max")

        # Fill na
        for col in ["solar_pv_wacc", "onshore_wacc", "offshore_wacc", "hydro_wacc", "geothermal_wacc", "bioenergy_wacc"]:
            country_waccs.loc[country_waccs[col].isnull(), col] = country_waccs[f"{col}_max"]

        return country_waccs
    
    
    
    def calculate_lcoe_shares(self, df):
        
        # Calculate OPEX share
        df["OPEX_LCOE_Uniform"] = df["Calculated_OPEX"] / df["electricity_production"] / (df["Uniform_LCOE"] / 1000) * 100
        df["OPEX_LCOE_Country"] = df["Calculated_OPEX"] / df["electricity_production"] / (df["Calculated_LCOE"] / 1000) * 100
        
        # Calculate CAPEX share
        df["CAPEX_LCOE_Uniform"] = df["Calculated_CAPEX"] / df["electricity_production"] / self.lifetime / (df["Uniform_LCOE"] / 1000) * 100
        df["CAPEX_LCOE_Country"] = df["Calculated_CAPEX"] / df["electricity_production"] / self.lifetime / (df["Calculated_LCOE"] / 1000) * 100
        
        # Calculate Financing Cost share
        df["WACC_LCOE_Uniform"] = 100 - df["OPEX_LCOE_Uniform"] - df["CAPEX_LCOE_Uniform"]
        df["WACC_LCOE_Country"] = 100 - df["OPEX_LCOE_Country"] - df["CAPEX_LCOE_Country"]
        
        return df
    
    
