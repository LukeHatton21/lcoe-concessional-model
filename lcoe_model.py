    def calculate_required_waccs_v2(self, data, lcoe=None, benchmark=None, allow_negative_irr=True, technology=None):

        def _npv_rate(r, capex0, cfa, n):
            # domain guard
            if r <= -1.0:
                return np.nan
            if np.isclose(r, 0.0):
                return -capex0 + cfa * n
            return -capex0 + cfa * (1.0 - (1.0 + r) ** (-n)) / r

        def _solve_irr_scalar(capex0, cfa, n):
            # Guardrails
            if np.isnan(capex0) or np.isnan(cfa) or np.isnan(n) or capex0 <= 0 or n <= 0:
                return np.nan

            n = int(round(n))

            # choose bracket
            lo = -0.99 if allow_negative_irr else 0.0
            hi = 2.0  # 200%

            f_lo = _npv_rate(lo, capex0, cfa, n)
            f_hi = _npv_rate(hi, capex0, cfa, n)

            if np.isnan(f_lo) or np.isnan(f_hi):
                return np.nan
            if f_lo == 0:
                return lo
            if f_hi == 0:
                return hi

            # no root in bracket
            if f_lo * f_hi > 0:
                if allow_negative_irr and f_lo < 0 and f_hi < 0:
                    return -1.0  # -100% IRR
                return np.nan

            # bisection
            for _ in range(100):
                mid = 0.5 * (lo + hi)
                f_mid = _npv_rate(mid, capex0, cfa, n)

                if np.isnan(f_mid):
                    return np.nan
                if np.isclose(f_mid, 0.0, atol=1e-12):
                    return mid

                if f_lo * f_mid < 0:
                    hi = mid
                    f_hi = f_mid
                else:
                    lo = mid
                    f_lo = f_mid

            return 0.5 * (lo + hi)

        # -------------------------
        # Preprocessing & constants
        # -------------------------
        data = data.drop_vars('Required_WACC', errors="ignore")

        latitudes = data.latitude.values
        longitudes = data.longitude.values

        annual_electricity_production = data['electricity_production']  # kWh for 1 MW
        initial_lcoe = data['Calculated_LCOE']  # USD/MWh for 1 MW

        annual_costs = data['Calculated_OPEX']  # USD/MW/year
        capital_costs = data['Calculated_CAPEX']  # USD for 1 MW

        # discount factor based on estimated WACC
        discount_factor = self.calculate_discount_factor_v1(data["Estimated_WACC"] / 100 + self.hurdle_rate)

        current_wacc = data["Estimated_WACC"] + self.hurdle_rate
        N = int(self.lifetime)

        # Calculate capture rate
        if technology == "Solar":
            capture_rate = self.solar_capture_rate
        elif technology=="Wind":
            capture_rate = self.wind_capture_rate
        else:
            capture_rate = 1

        # Normalize benchmark into a list of values to loop over
        if benchmark is None:
            benchmark_list = [None]
        elif np.isscalar(benchmark):
            benchmark_list = benchmark
            benchmark_list = [None] + benchmark_list
        else:
            # assume iterable of numbers
            benchmark_list = list(benchmark)
            benchmark_list = [None] + benchmark_list

        for bm in benchmark_list:
            # Construct a suffix for variable names
            if bm is None:
                suffix = ""
            else:
                suffix = f"{bm}"

            # -------------------------
            # Determine LCOE benchmark
            if bm is None:
                # wholesale-based benchmark
                lcoe_benchmark = self.wholesale_grids / 1000.0 * capture_rate # USD/kWh
            else:
                # retail-based benchmark
                benchmark_ratio = bm / 100.0
                lcoe_benchmark = self.retail_grids * benchmark_ratio * capture_rate / 1000.0  # USD/kWh

            # Store benchmark retail price
            data['Benchmark_Price'+ suffix] = self.retail_grids

            # -------------------------
            # Determine LCOE used
            # -------------------------
            if lcoe is None:
                lcoe_used = lcoe_benchmark
            else:
                # user-provided LCOE (assumed in USD/MWh) -> convert to USD/kWh
                lcoe_used = lcoe / 1000.0
            data['Benchmark_LCOE' + suffix] = lcoe_used

            # -------------------------
            # Benchmark ratio
            # -------------------------
            data['Benchmark_Ratio' + suffix] = data["Hurdle_Rate_LCOE"] / lcoe_used

            # -------------------------
            # Grant equivalent & WACC
            # -------------------------
            # Ensure denominator positive and LCOE above benchmark
            valid_mask = (
                                 (annual_electricity_production * lcoe_used - annual_costs) > 0
                         ) * (data["Hurdle_Rate_LCOE"] > lcoe_used)

            numerator = (
                    capital_costs
                    + annual_costs * discount_factor
                    - lcoe_used * annual_electricity_production * discount_factor
            )

            grant_equivalent = xr.where(
                np.isnan(lcoe_used) | ~valid_mask,
                np.nan,
                (numerator / capital_costs)
            )

            data['Grant_Equivalent_%' + suffix] = grant_equivalent
            data['Grant_Equivalent' + suffix] = grant_equivalent * data['Calculated_CAPEX']

            # Convert grant equivalence to CoC implications in nominal terms
            estimated_waccs = (data["Estimated_WACC"] + self.hurdle_rate) * (1 - data['Grant_Equivalent_%' + suffix])
            estimated_waccs = xr.where(
                np.isnan(lcoe_used) | ~valid_mask,
                np.nan,
                estimated_waccs
            )
            wacc_da = xr.DataArray(
                estimated_waccs,
                coords={"latitude": latitudes, "longitude": longitudes},
            )
            data['Benchmark_WACC' + suffix] = xr.where(
                np.isnan(initial_lcoe),
                np.nan,
                wacc_da
            )

            # WACC reductions
            data["WACC_Reductions" + suffix] = current_wacc - data["Benchmark_WACC" + suffix]
            data["WACC_Reductions" + suffix] = xr.where(
                data["WACC_Reductions" + suffix] < 0,
                -111,
                data["WACC_Reductions" + suffix],
            )

            # -------------------------
            # IRR at benchmark price
            benchmark_price_usd_per_kwh = lcoe_used
            annual_revenue = annual_electricity_production * benchmark_price_usd_per_kwh
            annual_costs_for_irr = annual_costs
            annual_cashflow = annual_revenue - annual_costs_for_irr

            irr_decimal = xr.apply_ufunc(
                np.vectorize(_solve_irr_scalar),
                capital_costs,
                annual_cashflow,
                kwargs={"n": N},
                vectorize=True,
                dask="parallelized",
                output_dtypes=[float],
            )

            data["Benchmark_IRR" + suffix] = xr.where(
                np.isnan(initial_lcoe) | np.isnan(lcoe_used),
                np.nan,
                irr_decimal * 100.0  # %
            )

            data["Benchmark_IRR" + suffix] = xr.where(
                ~np.isnan(initial_lcoe) & np.isnan(irr_decimal),
                -99,
                data["Benchmark_IRR" + suffix]
            )



        return data

    
