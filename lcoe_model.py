    def calculate_grant_abatement(self, data, benchmark=None):

        if benchmark is None:
            benchmark_list = [""]
        else:
            benchmark_list = benchmark
        benchmark_list = [None] + benchmark_list
        for benchmark in benchmark_list:
            if benchmark is not None:
                suffix = str(benchmark)
            else:
                suffix = ""
            data["Grant_Equivalent" + suffix] = xr.where(data["Grant_Equivalent" + suffix] < 0, -111,
                                                        data["Grant_Equivalent" + suffix])

            # Calculate the percentage grant required
            data["Grant_Equivalent_%" + suffix] = xr.where(data["Grant_Equivalent" + suffix] == -111, -111,
                                                              data["Grant_Equivalent_%" + suffix])

            # Calculate the abatement costs in USD per tCO2
            for additionality in ["", "_AF"]:
                data["abatement_cost" + suffix + additionality] = xr.where(data["Grant_Equivalent" + suffix] == -111, -111,
                                                              data["Grant_Equivalent" + suffix] / data["abatement_MW"+ additionality])
                valid = np.isfinite(data["abatement_cost" + suffix + additionality]) & (data["abatement_cost" + suffix + additionality] > 0)
                data["abatement_cost" + suffix + additionality] = xr.where(valid, data["abatement_cost" + suffix + additionality], np.nan)


                # Calculate abatements costs using CI in USD per tCO2
                data["abatement_cost_CI" + suffix + additionality] = xr.where(data["Grant_Equivalent" + suffix] == -111, -111,
                                                                     data["Grant_Equivalent" + suffix] / data[
                                                                         "abatement_CI" + additionality])
                valid = np.isfinite(data["abatement_cost_CI" + suffix + additionality]) & (data["abatement_cost_CI" + suffix + additionality] > 0)
                data["abatement_cost_CI" + suffix + additionality] = xr.where(valid, data["abatement_cost_CI" + suffix + additionality], np.nan)

        return data

    def calculate_lcoe(self, df: pd.DataFrame,
                       r_col: str,
                       lifetime_col: str = "Lifetime",
                       capex_col: str = "CAPEX",
                       om_pct_col: str = "O&M",
                       cf_col: str = "CF") -> pd.Series:
        """
        Calculate LCOE for each row when annual O&M is a fraction of CAPEX.

        Parameters
        ----------
        df : pd.DataFrame
            Must contain CAPEX, annual O&M percentage, capacity factor, and cost of capital.
        lifetime : str
            Column for project lifetime in years.
        capex_col : str
            Column for CAPEX (e.g., $/kW).
        om_pct_col : str
            Column for annual O&M as fraction of CAPEX (e.g., 0.03 for 3%/year).
        cf_col : str
            Column for capacity factor (0-1).
        r_col : str
            Column for cost of capital as fraction (e.g., 0.08 for 8%).

        Returns
        -------
        pd.Series
            LCOE per row (same index as df), in $/kWh if CAPEX is $/kW.
        """

        if df[lifetime_col].min() <= 0:
            raise ValueError("lifetime must be a positive integer")

        required = [capex_col, om_pct_col, cf_col, r_col, lifetime_col]
        missing = [c for c in required if c not in df.columns]
        if missing:
            raise KeyError(f"Missing required columns: {missing}")

        capex = pd.to_numeric(df[capex_col], errors="coerce")
        om_pct = pd.to_numeric(df[om_pct_col], errors="coerce")
        cf = pd.to_numeric(df[cf_col], errors="coerce")
        r = pd.to_numeric(df[r_col], errors="coerce")
        lifetime = pd.to_numeric(df[lifetime_col], errors="coerce")

        # Checks
        if capex.isna().any() or om_pct.isna().any() or cf.isna().any() or r.isna().any():
            raise ValueError("One or more required values are non-numeric or missing")
        if (cf <= 0).any() or (cf > 1).any():
            raise ValueError("capacity_factor must be in (0, 1]")
        if (r < 0).any():
            raise ValueError("cost_of_capital must be >= 0")
        if (om_pct < 0).any():
            raise ValueError("annual_om_pct must be >= 0")

        # CRF (special case r = 0)
        inflation_factor = 1.057 * 1.043
        crf = np.where(
            r == 0,
            1 / lifetime,
            (r * (1 + r) ** lifetime) / ((1 + r) ** lifetime - 1)
        )
        crf_hr = np.where(
            r == 0,
            1 / lifetime,
            ((r + self.hurdle_rate) * (1 + r + self.hurdle_rate) ** lifetime) / ((1 + r + self.hurdle_rate) ** lifetime - 1)
        )

        annual_production = (8760 * cf)
        if r_col == "bioenergy_wacc":
            annual_om = capex * om_pct * inflation_factor + annual_production * 0.004 * inflation_factor
        else:
            annual_om = capex * om_pct * inflation_factor
        if r_col == "geothermal_wacc":
            capex = capex

        lcoe = (capex * crf * inflation_factor + annual_om) / annual_production
        lcoe_hr = (capex * crf_hr * inflation_factor + annual_om) / annual_production
        nodiscount_lcoe = (capex * 1 / lifetime * inflation_factor + annual_om) / annual_production

        # Add to the dataframe (for 1 MW - here we multiply by 1000 to get $/MWh and to get electricity production in kWh)
        df["Calculated_LCOE"] = lcoe * 1000
        df["Hurdle_Rate_LCOE"] = lcoe_hr * 1000
        df["Undiscounted_LCOE"] = nodiscount_lcoe * 1000
        df["electricity_production"] = annual_production * 1000
        df["technical_potential"] = annual_production * 1000
        df["Calculated_CAPEX"] = capex * inflation_factor * 1000
        df["Calculated_OPEX"] = annual_om * 1000
        df["Estimated_WACC"] = r * 100
        df["CF"] = cf
        df["Lifetime"] = lifetime

        # Merge onto country dataset mapping
        country_grids = self.country_grids.rename({"land": "index"})
        country_df = country_grids.to_dataframe().reset_index()
        country_df = country_df.merge(df[["Country", "index", "Calculated_LCOE", "Hurdle_Rate_LCOE", "electricity_production", "Calculated_CAPEX", "Calculated_OPEX", "CF", "Lifetime", "Estimated_WACC", "technical_potential"]], how="left", on="index")
        country_ds = country_df.drop_duplicates(subset=["latitude", "longitude"]).set_index(
            ["latitude", "longitude"]).to_xarray()
        country_ds = country_ds.assign_coords({"latitude": country_ds.latitude, "longitude": country_ds.longitude})

        if r_col == "geothermal_wacc":
            country_ds = self.geothermal_distribution(country_ds)
            country_ds["technical_potential"] = country_ds["Capacity_MW"] * country_ds["CF"] * 8760 * 1e+03
            country_ds.drop_vars("Capacity_MW")
        elif r_col == "bioenergy_wacc":
            country_ds = self.bioenergy_distribution(country_ds)
            country_ds["technical_potential"] = country_ds["Capacity_MW"] * country_ds["CF"] * 8760 * 1e+03
            country_ds.drop_vars("Capacity_MW")
        elif r_col == "hydro_wacc":
            country_ds = self.hydropower_distribution(country_ds)
            country_ds["technical_potential"] = country_ds["Capacity_MW"] * country_ds["CF"] * 8760 * 1e+03
            country_ds.drop_vars("Capacity_MW")

        return country_ds

    def hydropower_distribution(self, country_ds):

        # Extract hydropower data
        hydro_reservoirs = self.GDW_reservoirs
        hydro_dams = self.GDW_barriers

        # Extract hydropower data
        hydro_res_capacity = hydro_reservoirs.fillna(0)
        hydro_dam_capacity = hydro_dams.fillna(0)

        # Create a unified dataframe
        hydro_unified = hydro_res_capacity + hydro_dam_capacity
        country_ds["Capacity_MW"] = hydro_unified

        cutoff = hydro_unified.mean()
        country_ds["Calculated_LCOE"] = country_ds["Calculated_LCOE"].where(country_ds["Capacity_MW"] > cutoff)
        country_ds["electricity_production"] = country_ds["electricity_production"].where(
            country_ds["Capacity_MW"] > cutoff)
        country_ds["technical_potential"] = 0

        return country_ds

    def bioenergy_distribution(self, country_ds):

        # Get bioenergy distribution
        bioenergy_potential = self.bio_potential
        bioenergy_potential = bioenergy_potential.squeeze("band", drop=True).to_dataset(name="potential").rename({"x": "longitude", "y": "latitude"})

        # Get grid lats
        target_lat = country_ds["latitude"].values
        target_lon = country_ds["longitude"].values

        # Use nearest-index approach
        lat_edges = np.concatenate([
            [target_lat[0] - (target_lat[1] - target_lat[0]) / 2],
            (target_lat[:-1] + target_lat[1:]) / 2,
            [target_lat[-1] + (target_lat[-1] - target_lat[-2]) / 2]
        ])
        lon_edges = np.concatenate([
            [target_lon[0] - (target_lon[1] - target_lon[0]) / 2],
            (target_lon[:-1] + target_lon[1:]) / 2,
            [target_lon[-1] + (target_lon[-1] - target_lon[-2]) / 2]
        ])
        bio_binned = (
            bioenergy_potential.groupby_bins("latitude", lat_edges, labels=target_lat).sum(dim="latitude").groupby_bins("longitude", lon_edges,labels=target_lon).sum(dim="longitude")
        )

        # Rename and assign coordinates
        bio_binned = bio_binned.rename({
            "latitude_bins": "latitude",
            "longitude_bins": "longitude"
        })
        bio_binned = bio_binned.assign_coords(
            latitude=target_lat,
            longitude=target_lon
        )

        # Back to DataArray
        cutoff = 19000
        country_ds["Capacity_MW"] = bio_binned["potential"]
        country_ds["Calculated_LCOE"] = country_ds["Calculated_LCOE"].where(country_ds["Capacity_MW"] > cutoff)
        country_ds["electricity_production"] = country_ds["electricity_production"].where(
            country_ds["Capacity_MW"] > cutoff)
        country_ds["technical_potential"] = 0

        return country_ds

    def geothermal_distribution(self, country_ds):

        # Extract geothermal distribution
        geothermal_data = self.geothermal_potential[["lon", "lat", "Pout_Gringarten_MW"]].rename(columns={"lon":"longitude", "lat":"latitude", "Pout_Gringarten_MW":"Capacity_MW"})

        # Get grid latitude and longitudes
        grid_lat = country_ds['latitude'].values
        grid_lon = country_ds['longitude'].values
        dlat = grid_lat[1] - grid_lat[0]
        dlon = grid_lon[1] - grid_lon[0]

        # Get plant locations from dataframe and get closest locations
        plant_lat = geothermal_data['latitude'].values
        plant_lon = geothermal_data['longitude'].values
        plant_capacity = geothermal_data["Capacity_MW"].values
        lat_idx = np.round((plant_lat - grid_lat[0]) / dlat).astype(int)
        lon_idx = np.round((plant_lon - grid_lon[0]) / dlon).astype(int)


        valid = (
                (lat_idx >= 0) & (lat_idx < len(grid_lat)) &
                (lon_idx >= 0) & (lon_idx < len(grid_lon))
        )
        lat_idx = lat_idx[valid]
        lon_idx = lon_idx[valid]
        plant_capacity = plant_capacity[valid]

        # Build empty mask and mark cells that contain at least one plant
        capacity_sum = np.zeros((len(grid_lat), len(grid_lon)), dtype=float)
        np.add.at(capacity_sum, (lat_idx, lon_idx), plant_capacity)

        # Apply onto the original dataframe and fix for locations with no data
        cutoff = 50
        country_ds["Capacity_MW"] = xr.DataArray(
            capacity_sum,
            coords={"latitude": country_ds["latitude"], "longitude": country_ds["longitude"]},
            dims=("latitude","longitude")
        )
        country_ds["Calculated_LCOE"] = country_ds["Calculated_LCOE"].where(country_ds["Capacity_MW"] > cutoff)
        country_ds["electricity_production"] = country_ds["electricity_production"].where(country_ds["Capacity_MW"] > cutoff)
        country_ds["technical_potential"] = 0


        return country_ds



    def calculate_other_renewables(self):

        # Extract the input files for renewables
        country_mapping = self.ren_mapping.copy()
